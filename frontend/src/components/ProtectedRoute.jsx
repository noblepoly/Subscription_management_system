import React from 'react';
import { Navigate, Outlet } from 'react-router-dom';
import { useAuth } from '../context/AuthContext';

export const ProtectedRoute = ({ allowedRoles = null }) => {
  const { isAuthenticated, role, loading } = useAuth();

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50">
        <div className="w-8 h-8 border-3 border-indigo-600/20 border-t-indigo-600 rounded-full animate-spin" />
      </div>
    );
  }

  if (!isAuthenticated) {
    return <Navigate to="/login" replace />;
  }

  if (allowedRoles && !allowedRoles.includes(role)) {
    // If user is CUSTOMER trying to access internal operations, bounce to /portal
    if (role === 'CUSTOMER') {
      return <Navigate to="/portal" replace />;
    }
    // If staff trying to access admin-only, bounce to /dashboard
    return <Navigate to="/dashboard" replace />;
  }

  return <Outlet />;
};
